/* --- ส่วนที่ 1: การประเมินร่างกายและค่าพื้นฐาน (Body Assessment) [cite: 2] --- */
-- ใช้อธิบายข้อมูลตั้งต้นของผู้ใช้งาน [cite: 3]

-- 1.1 ดัชนีมวลกาย (BMI - Body Mass Index) [cite: 4]
-- ประเมินความสมดุลระหว่างน้ำหนักกับส่วนสูง [cite: 5]
-- สูตร: BMI = น้ำหนักตัว(kg.) / (ส่วนสูง(m.)^2) [cite: 7, 8, 9, 10]
-- เกณฑ์ (Asia-Pacific): 
--   * ผอม < 18.5 [cite: 11, 12]
--   * ปกติ 18.5 - 22.9 [cite: 13]
--   * น้ำหนักเกิน 23.0 - 24.9 [cite: 14]
--   * โรคอ้วน >= 25.0 [cite: 15, 16]

-- 1.2 อัตราการเผาผลาญพื้นฐาน (BMR - Basal Metabolic Rate) [cite: 18]
-- ปริมาณพลังงานขั้นต่ำที่ร่างกายต้องการใช้ในขณะพักผ่อน [cite: 19]
-- สูตรชาย: BMR = (10 * น้ำหนักตัว(kg.)) + (6.25 * ส่วนสูง(cm.)) - (5 * อายุ(ปี)) + 5 [cite: 21, 22]
-- สูตรหญิง: BMR = (10 * น้ำหนักตัว(kg.)) + (6.25 * ส่วนสูง(cm.)) - (5 * อายุ(ปี)) - 161 [cite: 23, 24]

-- 1.3 พลังงานที่ใช้ต่อวัน (TDEE - Total Daily Energy Expenditure) [cite: 25]
-- ปริมาณพลังงานรวมที่ร่างกายเผาผลาญในหนึ่งวัน [cite: 26]
--   * ไม่ออกกำลังกาย หรือ นั่งโต๊ะ: TDEE = BMR * 1.2 [cite: 27]
--   * ออกกำลังกายเบา (1-3 วัน/สัปดาห์): TDEE = BMR * 1.375 [cite: 28]
--   * ออกกำลังกายปานกลาง (3-5 วัน/สัปดาห์): TDEE = BMR * 1.5 [cite: 29]
--   * ออกกำลังกายหนัก (6-7 วัน/สัปดาห์): TDEE = BMR * 1.725 [cite: 29]
--   * ออกกำลังกายหนักมาก หรือ นักกีฬา: TDEE = BMR * 1.9 [cite: 30, 31]


/* --- ส่วนที่ 2: การกำหนดเป้าหมาย (Goal Setting) [cite: 32, 33] --- */
-- นำค่า TDEE มาปรับลดหรือเพิ่มเป็นเปอร์เซ็นต์ เพื่อหา Target Calories [cite: 34, 35]

-- 2.1 ลดน้ำหนัก [cite: 36]
-- Target Calories = TDEE - (TDEE * 20%) [cite: 36]
-- เหตุผล: สร้างสภาวะ Calorie Deficit อย่างปลอดภัย [cite: 37, 38]
-- ** เงื่อนไขความปลอดภัย: ค่า Target ต้องไม่ต่ำกว่าค่า BMR (ถ้าคำนวณแล้วน้อยกว่า ให้ปรับ Target = BMR ทันที) [cite: 38]

-- 2.2 เพิ่มน้ำหนัก [cite: 39]
-- Target Calories = TDEE + (TDEE * 15%) [cite: 39]
-- เหตุผล: สร้างสภาวะ Calorie Surplus เพื่อสร้างกล้ามเนื้อ [cite: 40, 41]

-- 2.3 รักษาน้ำหนัก [cite: 41]
-- Target Calories = TDEE [cite: 41]
-- เหตุผล: รับพลังงานเท่ากับที่เผาผลาญเพื่อรักษาสมดุล [cite: 42, 43]


/* --- ส่วนที่ 3: การติดตามและคำนวณกิจกรรมรายวัน (Daily Tracking) [cite: 44] --- */
-- ใช้อธิบายการทำงานจริง (Input vs Output) [cite: 45]

-- 3.1 พลังงานรับเข้า (Energy In) [cite: 46]
-- Energy In = Food Calories + Drink Calories [cite: 47, 48]

-- 3.2 พลังงานใช้ออกจริง (Energy Out / Total Daily Energy Output) [cite: 49, 61]
-- ส่วนที่ 1: Baseline Expenditure = BMR * 1.2 (ค่าสำหรับกิจกรรมทั่วไป/ไม่ออกกำลังกาย) [cite: 51, 54, 55]
-- ส่วนที่ 2: Exercise Burn = Cardio Burn + Weight Training Burn [cite: 57, 60]
-- Total Daily Energy Output = Baseline Expenditure + Exercise Burn [cite: 64, 65]

-- 3.3 การคำนวณคาร์ดิโอ และ เวทเทรนนิ่ง (METs) [cite: 66]
-- พลังงานที่ใช้(kcal) = ค่า METs * น้ำหนักตัว(kg.) * ระยะเวลา(ชั่วโมง) [cite: 67, 68]
-- ค่ามาตรฐานอ้างอิง: เดินเร็ว(4.8 km/h) = 3.5 METs [cite: 70], เวทเทรนนิ่ง = 3.5 - 6.0 METs [cite: 71]

-- 3.4 ปริมาตรการฝึกรวม (Training Volume) [cite: 72]
-- ตัวชี้วัดภาระงานรวมที่กล้ามเนื้อได้รับ [cite: 73]
-- Volume (kg.) = น้ำหนักที่ยก(kg.) * จำนวนครั้ง(Reps) * จำนวนเซ็ต(Sets) [cite: 75]

-- 3.5 ศักยภาพการยกสูงสุด (1 Rep Max - 1RM) [cite: 76]
-- ทำนายการยกหนักที่สุด 1 ครั้ง เพื่อป้องกันการบาดเจ็บของมือใหม่ [cite: 78, 79, 80, 81]
-- 1RM = น้ำหนักที่ยก * (1 + (จำนวนครั้งที่ยก / 30)) [cite: 82, 83, 85] (30 คือค่าคงที่ทางสถิติ [cite: 84])


/* --- ส่วนที่ 4: การวิเคราะห์และโภชนาการ (Analysis & Nutrition) [cite: 86] --- */
-- ใช้อธิบายผลลัพธ์สุดท้ายและการแนะนำสารอาหาร [cite: 87]

-- 4.1 สมดุลพลังงาน (Energy Balance) [cite: 87]
-- Energy Balance = Energy Input - Total Daily Energy Output [cite: 88, 90]
-- เกณฑ์ประเมิน:
--   * ต่ำกว่าเป้า: กินน้อยกว่า (Target Calories - 10%) [cite: 92]
--   * ตามเป้า: กินอยู่ในช่วง (Target Calories +/- 10%) [cite: 93]
--   * เกินเป้า: กินมากกว่า (Target Calories + 10%) [cite: 94]

-- 4.2 สัดส่วนสารอาหาร (Macronutrients) คิดเป็น % ของพลังงานเป้าหมาย [cite: 95, 96, 114, 115]
--   * รักษาสุขภาพ: คาร์บ 50% | โปรตีน 20% | ไขมัน 30% [cite: 97]
--   * ลดไขมัน: คาร์บ 35% | โปรตีน 40% | ไขมัน 25% [cite: 98]
--   * สร้างกล้ามเนื้อ: คาร์บ 50% | โปรตีน 30% | ไขมัน 20% [cite: 99]

-- 4.3 การแปลงสารอาหารเป็นหน่วยกรัม (Grams Conversion) [cite: 100, 104]
-- โปรตีน(1g=4kcal) [cite: 101] : ปริมาณโปรตีน(g) = (Target Calories * สัดส่วนโปรตีน(%)) / 4 [cite: 105, 106, 109]
-- คาร์บ(1g=4kcal) [cite: 102]   : ปริมาณคาร์บ(g) = (Target Calories * สัดส่วนคาร์โบไฮเดรต(%)) / 4 [cite: 107, 110, 111]
-- ไขมัน(1g=9kcal) [cite: 103]   : ปริมาณไขมัน(g) = (Target Calories * สัดส่วนไขมัน(%)) / 9 [cite: 108, 112, 113]